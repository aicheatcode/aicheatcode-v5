// Imported records follow the existing D1 publication rules.
const state=initial();const original=new PromptCatalog(index,data.prompts).get('CSV-100000');
const edited={...original,title:'Published imported revision',text:'Verified replacement text',publishStatus:'published'};
state.overrides[edited.id]={...edited,publishStatus:'draft'};
let merged=new PromptCatalog(index,merge(data,state).prompts,state.deleted);
